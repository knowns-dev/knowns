func TestLoadCanonicalEvaluationFixture(t *testing.T) {
	fixture, err := LoadCanonicalEvaluationFixture()
	if err != nil {
		t.Fatalf("LoadCanonicalEvaluationFixture: %v", err)
	}
	if fixture.SchemaVersion != EvaluationFixtureSchemaVersion {
		t.Fatalf("schema version = %d", fixture.SchemaVersion)
	}
	if len(fixture.Cases) < 5 {
		t.Fatalf("case count = %d, want at least 5", len(fixture.Cases))
	}
	for _, tc := range fixture.Cases {
		if len(tc.Qrels) == 0 || len(tc.Modes) != 3 {
			t.Fatalf("case %q is missing qrels or evaluation modes", tc.ID)
		}
	}
}

func TestCommittedEvaluationBaselinesMatchCanonicalFixture(t *testing.T) {
	fixture, err := LoadCanonicalEvaluationFixture()
	if err != nil {
		t.Fatal(err)
	}
	pinned := PinnedSemanticRuntimeID()
	tests := []struct {
		path      string
		mode      string
		runtimeID string
		// optional marks a baseline that may legitimately be absent. CI no
		// longer generates the semantic and hybrid ones: the job that did
		// spent its whole budget indexing through Ollama on a CPU runner and
		// timed out, so it was removed. They are regenerated by hand now.
		// The keyword baseline is never optional: it needs no embedder, so
		// nothing can stop it from being committed.
		optional bool
	}{
		{"testdata/retrieval_evaluation_baseline.json", "keyword", "keyword", false},
		{"testdata/retrieval_evaluation_semantic_baseline.json", "semantic", pinned, true},
		{"testdata/retrieval_evaluation_hybrid_baseline.json", "hybrid", pinned, true},
	}
	for _, tt := range tests {
		t.Run(tt.mode, func(t *testing.T) {
			baseline, err := LoadEvaluationBaselineFile(tt.path)
			if err != nil {
				if tt.optional && errors.Is(err, os.ErrNotExist) {
					t.Skipf(
						"%s baseline not committed; regenerate it on a machine "+
							"serving %s with: knowns eval retrieval --mode %s "+
							"--runtime-id %s --baseline %s --update-baseline "+
							`--reason "<why>"`,
						tt.mode, tt.runtimeID, tt.mode, tt.runtimeID,
						// tt.path resolves against this package dir; the
						// command is run from the repository root.
						"internal/search/"+tt.path,
					)
				}
				t.Fatal(err)
			}
			if err := ValidateEvaluationBaseline(fixture, baseline, tt.mode, tt.runtimeID); err != nil {
				t.Fatalf("validate committed %s baseline: %v", tt.mode, err)
			}
		})
	}
}

