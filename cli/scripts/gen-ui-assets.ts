// Generates src/ui-assets.generated.ts: one `with { type: "file" }` import per ui/dist file,
// so `bun build --compile` embeds them in the binary.
import { existsSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const root = resolve(import.meta.dir, "..", "..");
const dist = join(root, "ui", "dist");

if (!existsSync(join(dist, "index.html"))) {
  console.log("ui/dist missing, building UI...");
  for (const cmd of [
    ["bun", "install"],
    ["bun", "run", "build"],
  ]) {
    const p = Bun.spawnSync(cmd, { cwd: join(root, "ui"), stdout: "inherit", stderr: "inherit" });
    if (p.exitCode !== 0) process.exit(p.exitCode ?? 1);
  }
}

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    const f = join(dir, n);
    return statSync(f).isDirectory() ? walk(f) : [f];
  });
}

const files = walk(dist).sort();
const lines = ["// @ts-nocheck", "// GENERATED by scripts/gen-ui-assets.ts. Do not edit.", ""];
files.forEach((f, i) => {
  const rel = relative(join(import.meta.dir, "..", "src"), f)
    .split("\\")
    .join("/");
  lines.push(`import a${i} from ${JSON.stringify(rel)} with { type: "file" };`);
});
lines.push("", "export const uiAssets: Record<string, Blob> = {");
files.forEach((f, i) => {
  const key = relative(dist, f).split("\\").join("/");
  lines.push(`  ${JSON.stringify(key)}: Bun.file(a${i}),`);
});
lines.push("};", "");
writeFileSync(join(import.meta.dir, "..", "src", "ui-assets.generated.ts"), lines.join("\n"));
console.log(`generated ${files.length} ui assets`);
