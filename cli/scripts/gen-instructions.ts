// Generates src/domain/instructions/embedded.generated.ts from the same source trees Go embeds:
//   internal/instructions/skills/kn-*          (`//go:embed kn-*`)
//   internal/instructions/guidelines/unified/*.md  (`//go:embed unified/*.md`)
// Every file is stored as an exact UTF-8 string, so a regenerated module reproduces the bytes Go
// embeds. Like go:embed, a directory walk skips names starting with "." or "_".
// `bun scripts/gen-instructions.ts --check` fails when the committed module is stale.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const root = resolve(import.meta.dir, "..", "..");
const skillsDir = join(root, "internal", "instructions", "skills");
const guidelinesDir = join(root, "internal", "instructions", "guidelines", "unified");
const out = join(import.meta.dir, "..", "src", "domain", "instructions", "embedded.generated.ts");

function walk(dir: string): string[] {
  return readdirSync(dir)
    .sort()
    .flatMap((n) => {
      if (n.startsWith(".") || n.startsWith("_")) return [];
      const f = join(dir, n);
      return statSync(f).isDirectory() ? walk(f) : [f];
    });
}

function text(file: string): string {
  const bytes = readFileSync(file);
  const s = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true }).decode(bytes);
  if (!Buffer.from(s, "utf8").equals(bytes)) throw new Error(`${file}: not losslessly UTF-8`);
  return s;
}

function entries(base: string, files: string[]): string {
  return files
    .map(
      (f) =>
        `  ${JSON.stringify(relative(base, f).split("\\").join("/"))}: ${JSON.stringify(text(f))},`,
    )
    .join("\n");
}

/** Skills: every `kn-*` directory, with all files below it. */
export function skillFiles(): string[] {
  return readdirSync(skillsDir)
    .sort()
    .filter((n) => n.startsWith("kn-") && statSync(join(skillsDir, n)).isDirectory())
    .flatMap((n) => walk(join(skillsDir, n)));
}

/** Guidelines: the top-level unified/*.md files. */
export function guidelineFiles(): string[] {
  return readdirSync(guidelinesDir)
    .sort()
    .filter((n) => n.endsWith(".md") && statSync(join(guidelinesDir, n)).isFile())
    .map((n) => join(guidelinesDir, n));
}

export function render(): string {
  return [
    "// GENERATED by scripts/gen-instructions.ts from internal/instructions. Do not edit.",
    "// test/cli/commands/init-embedded.test.ts fails when this file drifts from its sources.",
    "",
    "/** Embedded built-in skills (internal/instructions/skills/kn-*), keyed by path under skills/. */",
    "export const skillFiles: Record<string, string> = {",
    entries(skillsDir, skillFiles()),
    "};",
    "",
    "/** Embedded guideline templates (internal/instructions/guidelines/unified/*.md). */",
    "export const guidelineFiles: Record<string, string> = {",
    entries(guidelinesDir, guidelineFiles()),
    "};",
    "",
  ].join("\n");
}

if (import.meta.main) {
  if (!existsSync(skillsDir)) throw new Error(`missing ${skillsDir}`);
  const next = render();
  if (process.argv.includes("--check")) {
    if (!existsSync(out) || readFileSync(out, "utf8") !== next) {
      console.error("embedded.generated.ts is stale; run `bun run gen`");
      process.exit(1);
    }
  } else {
    writeFileSync(out, next);
    console.log(
      `generated ${skillFiles().length} skill files, ${guidelineFiles().length} guidelines`,
    );
  }
}
