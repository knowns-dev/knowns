/** Doc ids are random (doc-<hex>) and name history files; record them per doc path to mask stably. */
function recordDocIds(sb: Sandbox, dest: string, files: string[]) {
  for (const rel of files) {
    if (!rel.startsWith(".knowns/docs/") || !rel.endsWith(".md")) continue;
    const head = readFileSync(join(dest, rel), "utf8").replace(/^\uFEFF/, "");
    const m = /^id: (doc-[0-9a-f]+)$/m.exec(head);
    if (m?.[1]) sb.ids[`docid:${rel.slice(".knowns/docs/".length, -3)}`] = m[1];
  }
}

function ids(sb: Sandbox, name: string, value: string) {
  sb.ids[name] = value;
}

