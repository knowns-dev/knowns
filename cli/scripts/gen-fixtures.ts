// Golden fixture oracle (TSR-871S29).
//
// Drives the Go 0.34.1 binary through its CLI only to produce fixture projects under
// cli/test/fixtures/<name>/. Nothing under .knowns/ is hand-written: every byte comes from
// the Go binary, except the BOM fixture, which prepends a UTF-8 BOM to files the Go binary wrote
// (the same mutation tests/e2e_os_regression_test.go applies).
//
// Usage:
//   bun scripts/gen-fixtures.ts            regenerate cli/test/fixtures (replaces generated dirs)
//   bun scripts/gen-fixtures.ts --verify   regenerate into a temp dir and compare the masked
//                                          digest with the committed manifest (reproducibility)
//   bun scripts/gen-fixtures.ts --out DIR  write somewhere else
//
// Environment:
//   KNOWNS_GO_BIN   use this prebuilt Go binary (must report version 0.34.1) instead of building
//
// Reproducibility: the Go binary has no clock or RNG override, so timestamps and random IDs differ
// on every run. The script records the generated IDs in manifest.json (logical name -> id) and a
// `digest` computed over the file tree after masking every volatile value (timestamps, ids,
// hashes). Two runs produce different bytes and the same digest, which --verify checks.
import { createHash } from "node:crypto";
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  realpathSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve, sep } from "node:path";

const GO_VERSION = "0.34.1";
const REPO = resolve(import.meta.dir, "..", "..");
const DEFAULT_OUT = resolve(import.meta.dir, "..", "test", "fixtures");

interface Manifest {
  goVersion: string;
  note: string;
  fixtures: Record<string, FixtureEntry>;
}

interface FixtureEntry {
  description: string;
  /** Logical name -> real id/path generated by this run. */
  ids: Record<string, string>;
  /** Files (relative to the fixture dir, forward slashes) in the fixture. */
  files: string[];
  /** sha256 over the file tree with volatile values masked; stable across regenerations. */
  digest: string;
  /** Files that carry a UTF-8 BOM. */
  bomFiles?: string[];
  /**
   * Leaf directories with no files (forward slashes). Git does not track them, so a clean clone
   * lacks them; test/helpers/fixture-dirs.ts recreates them before any test copies a fixture.
   */
  emptyDirs?: string[];
}

function parseFlags(argv: string[]) {
  const flags = { verify: false, out: DEFAULT_OUT };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--verify") flags.verify = true;
    else if (a === "--out") flags.out = resolve(argv[++i] ?? "");
    else throw new Error(`unknown flag ${a}`);
  }
  return flags;
}

function goBinary(work: string): string {
  const fromEnv = process.env.KNOWNS_GO_BIN;
  const bin = fromEnv ? resolve(fromEnv) : join(work, "knowns-go", "knowns");
  if (!fromEnv) {
    const res = Bun.spawnSync(
      [
        "go",
        "build",
        "-ldflags",
        `-X github.com/howznguyen/knowns/internal/util.Version=${GO_VERSION}`,
        "-o",
        bin,
        "./cmd/knowns",
      ],
      { cwd: REPO, stdout: "inherit", stderr: "inherit" },
    );
    if (res.exitCode !== 0) throw new Error("go build failed");
  }
  const v = Bun.spawnSync([bin, "--version"], { env: { ...process.env, NO_UPDATE_CHECK: "1" } });
  const text = v.stdout.toString();
  if (!text.includes(GO_VERSION)) {
    throw new Error(`Go binary must report ${GO_VERSION}, got: ${text.trim()}`);
  }
  return bin;
}

/** A scratch HOME + project directory driven through the Go CLI. */
class Sandbox {
  readonly home: string;
  readonly project: string;
  readonly ids: Record<string, string> = {};
  /** `--json` outputs of the Go CLI, written to <fixture>/_api/<name>.json by snapshot(). */
  readonly api: Record<string, string> = {};

  constructor(
    private readonly bin: string,
    root: string,
    name: string,
  ) {
    this.home = join(root, `${name}-home`);
    this.project = join(root, name);
    mkdirSync(this.home, { recursive: true });
    mkdirSync(this.project, { recursive: true });
    Bun.spawnSync(["git", "init", "-q", "."], { cwd: this.project });
  }

  private env(): Record<string, string> {
    return {
      PATH: process.env.PATH ?? "",
      HOME: this.home,
      USERPROFILE: this.home,
      TZ: "UTC",
      NO_COLOR: "1",
      NO_UPDATE_CHECK: "1",
      CI: "1",
      KNOWN_LSP_AUTO_INSTALL: "0",
      KNOWNS_RUNTIME_INLINE: "1",
      KNOWNS_SEMANTIC_RUNTIME_DISABLED: "1",
      GIT_CONFIG_GLOBAL: "/dev/null",
      GIT_CONFIG_SYSTEM: "/dev/null",
    };
  }

  /** Runs the CLI; throws on non-zero exit unless `allowFail`. Returns stdout+stderr. */
  kn(args: string[], allowFail = false): string {
    const res = Bun.spawnSync([this.bin, ...args, "--plain"], {
      cwd: this.project,
      env: this.env(),
    });
    const out = res.stdout.toString() + res.stderr.toString();
    if (res.exitCode !== 0 && !allowFail) {
      throw new Error(`knowns ${args.join(" ")} exited ${res.exitCode}:\n${out}`);
    }
    return out;
  }

  /** Runs a read command with `--json` and stores the output as the API golden `name`. */
  json(name: string, args: string[]) {
    const res = Bun.spawnSync([this.bin, ...args, "--json"], {
      cwd: this.project,
      env: this.env(),
    });
    if (res.exitCode !== 0) {
      throw new Error(
        `knowns ${args.join(" ")} --json exited ${res.exitCode}:\n${res.stderr.toString()}`,
      );
    }
    // Template.path is absolute; keep machine-specific scratch paths out of the committed output.
    let text = res.stdout.toString();
    const spellings = [...new Set([this.project, realpathSync(this.project)])];
    for (const abs of spellings.sort((a, b) => b.length - a.length)) {
      text = text.replaceAll(abs.replaceAll("\\", "\\\\"), "<project>");
    }
    JSON.parse(text); // fail loudly if the CLI printed anything that is not JSON
    this.api[name] = text;
  }

  /** Runs a CLI command and records the id matched by `pattern` under `name`. */
  capture(name: string, pattern: RegExp, args: string[]): string {
    const out = this.kn(args);
    const m = pattern.exec(out);
    if (!m?.[1])
      throw new Error(`could not find ${pattern} in output of ${args.join(" ")}:\n${out}`);
    this.ids[name] = m[1];
    return m[1];
  }

  task(name: string, title: string, ...flags: string[]): string {
    return this.capture(name, /Created task (\S+):/, ["task", "create", title, ...flags]);
  }

  doc(name: string, title: string, ...flags: string[]): string {
    return this.capture(name, /Created doc: (\S+)/, ["doc", "create", title, ...flags]);
  }

  decision(name: string, title: string, ...flags: string[]): string {
    return this.capture(name, /@decision\/(\S+)/, ["decision", "create", title, ...flags]);
  }

  memory(name: string, title: string, ...flags: string[]): string {
    return this.capture(name, /Created memory: (\S+) /, ["memory", "create", title, ...flags]);
  }

  init(name: string, ...flags: string[]) {
    this.kn(["init", name, "--no-wizard", "--no-open", ...flags]);
  }

  /** Copies the portable parts of the project (and any global memory) into dest. */
  snapshot(dest: string): string[] {
    rmSync(dest, { recursive: true, force: true });
    const src = join(this.project, ".knowns");
    cpSync(src, join(dest, ".knowns"), {
      recursive: true,
      filter: (p) => {
        const rel = relative(src, p).split(sep).join("/");
        // Runtime-only state: search index/locks, history lock files, sqlite sidecars.
        if (rel === ".search" || rel.startsWith(".search/")) return false;
        if (rel === "history/locks" || rel.startsWith("history/locks/")) return false;
        return true;
      },
    });
    for (const [name, text] of Object.entries(this.api)) {
      mkdirSync(join(dest, "_api"), { recursive: true });
      writeFileSync(join(dest, "_api", `${name}.json`), text);
    }
    const globalMemory = join(this.home, ".knowns", "memory");
    if (existsSync(globalMemory) && readdirSync(globalMemory).length > 0) {
      cpSync(globalMemory, join(dest, "_home", ".knowns", "memory"), { recursive: true });
    }
    return listFiles(dest);
  }
}

/** Leaf directories under root that hold no entries, as forward-slash paths relative to it. */
function listEmptyDirs(root: string): string[] {
  const out: string[] = [];
  const walk = (dir: string) => {
    const names = readdirSync(dir).sort();
    if (names.length === 0 && dir !== root) out.push(relative(root, dir).split(sep).join("/"));
    for (const name of names) {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) walk(p);
    }
  };
  walk(root);
  return out;
}

function emptyDirsField(root: string): { emptyDirs?: string[] } {
  const dirs = listEmptyDirs(root);
  return dirs.length > 0 ? { emptyDirs: dirs } : {};
}

function listFiles(root: string): string[] {
  const out: string[] = [];
  const walk = (dir: string) => {
    for (const name of readdirSync(dir).sort()) {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) walk(p);
      else out.push(relative(root, p).split(sep).join("/"));
    }
  };
  walk(root);
  return out;
}

