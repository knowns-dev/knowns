function generate(outDir: string): Manifest {
  const work = mkdtempSync(join(tmpdir(), "knowns-fixtures-"));
  try {
    const bin = goBinary(work);
    const manifest: Manifest = {
      goVersion: GO_VERSION,
      note: "Generated by scripts/gen-fixtures.ts from the Go binary. Do not edit by hand.",
      fixtures: {},
    };
    mkdirSync(outDir, { recursive: true });
    for (const [name, scenario] of Object.entries(scenarios)) {
      const sb = new Sandbox(bin, work, name);
      const result = scenario(sb);
      const dest = join(outDir, name);
      const files = sb.snapshot(dest);
      recordDocIds(sb, dest, files);
      const mask = makeMasker(sb.ids);
      manifest.fixtures[name] = {
        description: result.description,
        ids: sb.ids,
        files,
        digest: digestOf(
          dest,
          mask,
          process.env.KNOWNS_FIXTURE_DUMP_MASKED
            ? join(process.env.KNOWNS_FIXTURE_DUMP_MASKED, name)
            : undefined,
        ),
        ...(result.bomFiles ? { bomFiles: result.bomFiles } : {}),
        ...emptyDirsField(dest),
      };
    }
    writeFileSync(join(outDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
    return manifest;
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

function main() {
  const flags = parseFlags(process.argv.slice(2));
  if (flags.verify) {
    const committedPath = join(DEFAULT_OUT, "manifest.json");
    const committed = JSON.parse(readFileSync(committedPath, "utf8")) as Manifest;
    const tmp = mkdtempSync(join(tmpdir(), "knowns-fixtures-verify-"));
    try {
      const fresh = generate(tmp);
      let bad = 0;
      for (const name of Object.keys(committed.fixtures)) {
        const a = committed.fixtures[name]?.digest;
        const b = fresh.fixtures[name]?.digest;
        if (a !== b) {
          bad++;
          console.error(`DIGEST MISMATCH ${name}: committed ${a} fresh ${b}`);
        }
      }
      if (bad > 0) process.exit(1);
      console.log(`fixtures reproducible: ${Object.keys(committed.fixtures).length} digests match`);
    } finally {
      rmSync(tmp, { recursive: true, force: true });
    }
    return;
  }
  for (const name of Object.keys(scenarios)) {
    rmSync(join(flags.out, name), { recursive: true, force: true });
  }
  mkdirSync(dirname(join(flags.out, "x")), { recursive: true });
  const manifest = generate(flags.out);
  for (const [name, entry] of Object.entries(manifest.fixtures)) {
    console.log(`${name}: ${entry.files.length} files, digest ${entry.digest.slice(0, 12)}`);
  }
}

main();
