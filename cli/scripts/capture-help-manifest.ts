// Regenerates src/cli/core/help-manifest.generated.ts from the Go binary (the parity oracle).
//
// The manifest is the 0.34.1 root command set: every root command's name and one-line summary,
// plus the hidden root commands (they take part in cobra's name padding and in lookup).
// The TypeScript root help lists these so `knowns --help` is complete while commands are still
// being ported; a command that is not ported yet shows up here but fails honestly when run.
// Usage: KNOWNS_GO_BIN=/path/to/knowns bun scripts/capture-help-manifest.ts [--out <file>]
// test/cli/registry.test.ts runs it with --out and fails if the committed file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const cliDir = resolve(import.meta.dir, "..");
const repo = resolve(cliDir, "..");
const goBin = process.env.KNOWNS_GO_BIN;
if (!goBin) {
  console.error("set KNOWNS_GO_BIN to a Go knowns binary");
  process.exit(2);
}

const r = Bun.spawnSync([goBin, "--help"], {
  env: { ...process.env, NO_COLOR: "1", NO_UPDATE_CHECK: "1", CI: "1" },
  cwd: "/",
});
const help = r.stdout.toString();

interface Entry {
  name: string;
  short: string;
  hidden: boolean;
}
const entries: Entry[] = [];
let inGroups = false;
for (const line of help.split("\n")) {
  if (line === "Options:") break;
  if (/^[A-Z].*:$/.test(line)) {
    inGroups = true;
    continue;
  }
  const m = /^ {2}(\S+) +(.+)$/.exec(line);
  if (inGroups && m?.[1] && m[2]) entries.push({ name: m[1], short: m[2], hidden: false });
}

// Hidden root commands come from the contract snapshot Go already maintains.
const contract = readFileSync(join(repo, "internal/cli/testdata/command-contract.txt"), "utf8");
for (const line of contract.split("\n")) {
  const cols = line.split("\t");
  const m = /^knowns (\S+)$/.exec(cols[0] ?? "");
  if (m?.[1] && cols[1]?.startsWith("hidden") && !entries.some((e) => e.name === m[1])) {
    entries.push({ name: m[1], short: "", hidden: true });
  }
}
entries.sort((a, b) => (a.name < b.name ? -1 : 1));

const body = entries
  .map(
    (e) =>
      `  { name: ${JSON.stringify(e.name)}, short: ${JSON.stringify(e.short)}, hidden: ${e.hidden} },`,
  )
  .join("\n");
const outIdx = process.argv.indexOf("--out");
const outFile =
  outIdx >= 0 && process.argv[outIdx + 1]
    ? resolve(process.argv[outIdx + 1] as string)
    : join(cliDir, "src/cli/core/help-manifest.generated.ts");
writeFileSync(
  outFile,
  `// GENERATED by scripts/capture-help-manifest.ts from the Go 0.34.1 binary. Do not edit.
// Gated by test/cli/golden.test.ts: the root help rendered from this manifest must equal Go's.

export interface ManifestEntry {
  name: string;
  short: string;
  hidden: boolean;
}

export const ROOT_MANIFEST: readonly ManifestEntry[] = [
${body}
];
`,
);
console.log(`wrote ${entries.length} entries`);
